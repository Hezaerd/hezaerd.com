"""Generate src/data/land.ts from Natural Earth's 110m land polygons."""

import base64
import json
import math
import textwrap
import urllib.request
from pathlib import Path

SOURCE = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_land.geojson"
OUTPUT = Path(__file__).resolve().parent.parent / "src" / "data" / "land.ts"
STEP = 1
WIDTH, HEIGHT = 360 // STEP, 180 // STEP


def rasterize(features: list[dict]) -> bytearray:
    mask = bytearray((WIDTH * HEIGHT + 7) // 8)
    for feature in features:
        geometry = feature["geometry"]
        polygons = geometry["coordinates"]
        if geometry["type"] == "Polygon":
            polygons = [polygons]
        for rings in polygons:
            edges = [edge for ring in rings for edge in zip(ring, ring[1:])]
            for row in range(HEIGHT):
                lat = 90 - (row + 0.5) * STEP
                intersections = sorted(
                    west + (east - west) * (lat - south) / (north - south)
                    for (west, south), (east, north) in edges
                    if (south > lat) != (north > lat)
                )
                for left, right in zip(intersections[::2], intersections[1::2], strict=True):
                    start = max(0, math.ceil((left + 180) / STEP - 0.5))
                    end = min(WIDTH, math.ceil((right + 180) / STEP - 0.5))
                    for col in range(start, end):
                        bit = row * WIDTH + col
                        mask[bit // 8] |= 1 << (bit % 8)
    return mask


def main() -> None:
    with urllib.request.urlopen(SOURCE, timeout=30) as source:
        features = json.load(source)["features"]
    packed = base64.b64encode(rasterize(features)).decode("ascii")
    lines = " +\n".join(f'  "{line}"' for line in textwrap.wrap(packed, 112))
    OUTPUT.write_text(
        f"""// Generated by scripts/land-mask.py from Natural Earth 110m land.
const mask = atob(
{lines},
);

export function isLand(latDeg: number, lonDeg: number): boolean {{
  const row = Math.min({HEIGHT - 1}, Math.max(0, Math.floor((90 - latDeg) / {STEP})));
  const lon = (((lonDeg + 180) % 360) + 360) % 360;
  const col = Math.floor(lon / {STEP});
  const bit = row * {WIDTH} + col;
  return (mask.charCodeAt(bit >> 3) & (1 << (bit & 7))) !== 0;
}}
""",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
